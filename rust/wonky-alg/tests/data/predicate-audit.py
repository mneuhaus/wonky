mpmath.mp.prec = 64


def certified_sign(terms):
    """terms: list of (coefficient Fraction, [radicand Fraction...]) meaning c * prod sqrt(r)."""
    for prec in (256, 4096, 32768):
        mpmath.iv.prec = prec
        total = mpmath.iv.mpf(0)
        for c, rads in terms:
            term = mpmath.iv.mpf(c.numerator) / c.denominator
            for r in rads:
                term *= mpmath.iv.sqrt(mpmath.iv.mpf(r.numerator) / r.denominator)
            total += term
        if total.a > 0:
            return 1
        if total.b < 0:
            return -1
    expr = sum(
        sp.Rational(c.numerator, c.denominator)
        * sp.Mul(*[sp.sqrt(sp.Rational(r.numerator, r.denominator)) for r in rads])
        for c, rads in terms
    )
    if expr == 0 or sp.minimal_polynomial(expr, X) == X:
        return 0
    raise AssertionError(f"sign not certified at 32768 bits: {terms}")


def bits(v):
    return f"{struct.unpack('<Q', struct.pack('<d', v))[0]:016x}"


MIN_MAG, MAX_MAG = 1.0e-150, 1.0e150


def in_range(v):
    return v == 0.0 or (abs(v) >= MIN_MAG and abs(v) <= MAX_MAG)


def nearest_double_of(terms):
    mpmath.mp.prec = 200
    s = mpmath.mpf(0)
    for c, rads in terms:
        t = mpmath.mpf(c.numerator) / c.denominator
        for r in rads:
            t *= mpmath.sqrt(mpmath.mpf(r.numerator) / r.denominator)
        s += t
    return float(s)


def dyadic(scale=6):
    return rng.randint(-2**10, 2**10) / 2 ** rng.randint(0, scale)


def sum3_terms(a, ts):
    return [(F(a), [])] + [(F(c), [F(r)]) for c, r in ts]


