def prove_identities():
    a, b, r, u, v, t = sp.symbols("a b r u v t", real=True)
    # Sign-aware squaring (radical3 exact_sign, Radical field_sign, rational::Quadratic):
    # (A + B sqrt r)(A - B sqrt r) = A^2 - r B^2; for sign(A) = -sign(B) != 0 the
    # conjugate A - B sqrt r has sign(A), so sign(A + B sqrt r) = sign(A) sign(A^2 - r B^2).
    rp = sp.Symbol("rp", positive=True)
    assert sp.expand((a + b * sp.sqrt(rp)) * (a - b * sp.sqrt(rp)) - (a**2 - rp * b**2)) == 0
    # Multiquadratic basis product (radical3 product, Radical field_mul):
    # sqrt(prod_{i in I} r_i) sqrt(prod_{j in J} r_j) = sqrt(prod_{I xor J}) prod_{I and J} r_k.
    rs = sp.symbols("r0 r1 r2", positive=True)
    root = lambda mask: sp.Mul(*[sp.sqrt(rs[k]) for k in range(3) if mask >> k & 1])
    for i in range(8):
        for j in range(8):
            lhs = root(i) * root(j)
            rhs = root(i ^ j) * sp.Mul(*[rs[k] for k in range(3) if (i & j) >> k & 1])
            assert sp.simplify(lhs - rhs) == 0
    # Denesting (Radical::quadratic_sqrt): with N = a^2 - b^2 r = s^2, u = (a + s)/2,
    # v = (a - s)/2: (sqrt u + sqrt v)^2 = a + 2 sqrt(uv) and 4uv = a^2 - s^2 = b^2 r.
    s = sp.Symbol("s", nonnegative=True)
    uu, vv = (a + s) / 2, (a - s) / 2
    assert sp.expand(uu + vv - a) == 0
    assert sp.expand(4 * uu * vv - (a**2 - s**2)) == 0
    # Cramer / triple-product corner (wonky-blend chamfer intersection).
    na, nb, nc = (sp.Matrix(sp.symbols(f"{p}0:3")) for p in "abc")
    da, db, dc = sp.symbols("da db dc")
    det = na.dot(nb.cross(nc))
    point = (da * nb.cross(nc) + db * nc.cross(na) + dc * na.cross(nb)) / det
    for n, d in [(na, da), (nb, db), (nc, dc)]:
        assert sp.simplify(n.dot(point) - d) == 0
    # Chamfer spring point: |w t / sqrt(t.t)|^2 = w^2.
    tv = sp.Matrix(sp.symbols("t0:3", real=True))
    w = sp.Symbol("w", positive=True)
    assert sp.simplify((w * tv / sp.sqrt(tv.dot(tv))).dot(w * tv / sp.sqrt(tv.dot(tv))) - w**2) == 0
    # Projective half-angle circle chart (a1 Branch::Circle): unit circle, and
    # a quadric pulled back has degree <= 4, so a seam root has multiplicity 4 - deg.
    cx, cy, den = 1 - t**2, 2 * t, 1 + t**2
    assert sp.simplify(cx**2 + cy**2 - den**2) == 0
    # Plane x revolution (a1 plane_revolution, parallel cylinders): with
    # p = n rhs / n2 + u (-ny, nx), |p|^2 = rhs^2 / n2 + n2 u^2.
    nx, ny, rhs = sp.symbols("nx ny rhs", real=True)
    n2 = nx**2 + ny**2
    px, py = nx * rhs / n2 - u * ny, ny * rhs / n2 + u * nx
    assert sp.simplify(px**2 + py**2 - (rhs**2 / n2 + n2 * u**2)) == 0
    # Coaxial meridian reduction (a1 revolutions): x^2 + y^2 = (base + slope z)^2
    # substituted into x^2 + y^2 + c3 z + c9 z^2 + c0.
    base, slope, c0, c3, c9, z = sp.symbols("base slope c0 c3 c9 z")
    lhs = (base + slope * z) ** 2 + c3 * z + c9 * z**2 + c0
    rhs2 = (c0 + base**2) + (c3 + 2 * base * slope) * z + (c9 + slope**2) * z**2
    assert sp.expand(lhs - rhs2) == 0
    # Power <-> Bernstein basis change (wonky-alg bernstein.rs), degrees 0..6.
    for n in range(7):
        coeffs = sp.symbols(f"p0:{n + 1}")
        power = sum(coeffs[j] * t**j for j in range(n + 1))
        bern = [
            sum(sp.binomial(k, j) / sp.binomial(n, j) * coeffs[j] for j in range(k + 1))
            for k in range(n + 1)
        ]
        back = sum(bern[k] * sp.binomial(n, k) * t**k * (1 - t) ** (n - k) for k in range(n + 1))
        assert sp.expand(back - power) == 0
    return 9


# ------------------------------------------------------------- algebraic roots


def ev(c, q):
    acc = F(0)
    for coef in reversed(c):
        acc = acc * q + coef
    return acc


def imul(a, b):
    p = [a[0] * b[0], a[0] * b[1], a[1] * b[0], a[1] * b[1]]
    return min(p), max(p)


def iv_eval(c, s, t):
    lo = hi = F(0)
    for coef in reversed(c):
        lo, hi = imul((lo, hi), (s, t))
        lo, hi = lo + coef, hi + coef
    return lo, hi


class Root:
    """A rational root, or (irreducible monic f, index, isolating interval)."""

    def __init__(self, value=None, f=None, index=None, iv=None):
        self.value, self.f, self.index, self.iv = value, f, index, iv

    def rational(self):
        return self.f is None

    def key(self):
        return ("q", self.value) if self.rational() else ("a", tuple(self.f), self.index)

    def refine(self):
        s, t = self.iv
        m = (s + t) / 2
        fm = ev(self.f, m)
        assert fm != 0, "irreducible factor of degree >= 2 has no rational root"
        self.iv = (m, t) if sgn(fm) == sgn(ev(self.f, s)) else (s, m)


def coeffs_of(poly):
    return [F(int(c.p), int(c.q)) for c in reversed(poly.all_coeffs())]


def real_roots(expr):
    """Distinct real roots in increasing order with multiplicities."""
    _, factors = sp.factor_list(sp.Poly(expr, X, domain=sp.QQ))
    out = []
    for f, m in factors:
        f = f.monic()
        c = coeffs_of(f)
        if f.degree() == 1:
            out.append((Root(value=-c[0]), m))
            continue
        for index, ((s, t), _) in enumerate(f.intervals()):
            s, t = F(int(s.p), int(s.q)), F(int(t.p), int(t.q))
            assert s < t and sgn(ev(c, s)) * sgn(ev(c, t)) < 0
            out.append((Root(f=c, index=index, iv=(s, t)), m))
    out.sort(key=functools.cmp_to_key(lambda a, b: cmp_roots(a[0], b[0])))
    return out


def cmp_rational(root, q):
    if root.rational():
        return sgn(root.value - q)
    while root.iv[0] <= q <= root.iv[1]:
        root.refine()
    return -1 if root.iv[1] < q else 1


def cmp_roots(a, b):
    if a.key() == b.key():
        return 0
    if a.rational():
        return -cmp_rational(b, a.value)
    if b.rational():
        return cmp_rational(a, b.value)
    # Distinct monic irreducible factors share no root; equal factors differ by index.
    while True:
        if a.iv[1] < b.iv[0]:
            return -1
        if b.iv[1] < a.iv[0]:
            return 1
        (a if a.iv[1] - a.iv[0] >= b.iv[1] - b.iv[0] else b).refine()


def sign_at(q_coeffs, root):
    if root.rational():
        return sgn(ev(q_coeffs, root.value))
    q = sp.Poly(list(reversed([sp.Rational(c.numerator, c.denominator) for c in q_coeffs])), X)
    f = sp.Poly(list(reversed([sp.Rational(c.numerator, c.denominator) for c in root.f])), X)
    if q.rem(f).is_zero:
        return 0
    while True:
        lo, hi = iv_eval(q_coeffs, *root.iv)
        if lo > 0:
            return 1
        if hi < 0:
            return -1
        root.refine()


