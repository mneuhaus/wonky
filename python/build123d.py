def _load_private(module_name):
    """A wonky module next to the shim (python/<module>.py), loaded once by path, or None if absent.

    Loaded by path: the runner starts Python with -I, so this directory is not
    on sys.path, and names starting with "_" are not importable by models.
    """
    module = _sys.modules.get(module_name)
    if module is not None:
        return module
    path = _os.path.join(_SHIM_DIR, f"{module_name}.py")
    if not _os.path.isfile(path):
        return None
    from importlib import util as _util
    spec = _util.spec_from_file_location(module_name, path)
    module = _util.module_from_spec(spec)
    _sys.modules[module_name] = module
    try:
        spec.loader.exec_module(module)
    except BaseException:
        del _sys.modules[module_name]
        raise
    return module


# Implementation modules in dependency order; the core is required.
_MODULES = ("_b3d_core", "_b3d_location", "_b3d_sketch", "_b3d_ops", "_b3d_query", "_b3d_blend")
_CLASS_ATTRIBUTES = {}
for _module_name in _MODULES:
    _module = _load_private(_module_name)
    if _module is None:
        if _module_name == "_b3d_core":
            raise ImportError("the Bend build123d shim needs python/_b3d_core.py")
        continue
    globals().update(getattr(_module, "SHIM_ATTRIBUTES", {}))
    for _name, _value in getattr(_module, "BUILD123D", {}).items():
        if _name not in _TABLE["names"]:
            raise RuntimeError(f"{_module_name} implements {_name!r}, which is not a build123d {__version__} name")
        globals()[_name] = _value
    _CLASS_ATTRIBUTES.update(getattr(_module, "CLASS_ATTRIBUTES", {}))
del _module_name, _module

