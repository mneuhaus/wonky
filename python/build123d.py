_KERNEL_GAPS.update({"Sketch.fillet": _GAP_FILLET, "Sketch.chamfer": _GAP_CHAMFER})
for _owner in ("Face", "Wire", "Edge"):
    _KERNEL_GAPS[f"{_owner}.mirror"] = _GAP_MIRROR
