def _note(name, entry):
    """Why a sentinel is one, appended to its capability message."""
    if name in _KERNEL_GAPS:
        return f"; {_KERNEL_GAPS[name]}"
    module = entry.get("module") or ""
    if name.startswith("import_") and module in _READER_MODULES:
        # Decision 3 (docs/python-khana.md): external geometry files are not model inputs.
        return ("; it reads external geometry from a file, and the wonky package policy excludes external "
                "geometry: production geometry must be constructed in Bend (docs/python-khana.md)")
    if entry["origin"] == "ocp":
        return ("; it is an OpenCascade (OCP) name re-exported by build123d, and external geometry is disabled: "
                "production geometry must be constructed in Bend")
    if entry["origin"] != "reexport":
        return ""
    if module.split(".")[0] in _sys.stdlib_module_names:
        return f"; build123d re-exports it from '{module}', the Bend shim does not"
    return (f"; build123d re-exports it from the third-party package '{module.split('.')[0]}', "
            f"which wonky does not provide")


def _stdlib(source):
    """The standard-library object that build123d re-exports, or None if this Python lacks it.

    The table records only verified identities (scripts/python/build123d-names.py).
    A private home module of a newer Python (pathlib._local) falls back to its
    public parent (pathlib).
    """
    module_name, attribute = source
    parts = module_name.split(".")
    for depth in range(len(parts), 0, -1):
        try:
            module = _importlib.import_module(".".join(parts[:depth]))
        except ImportError:
            continue
        if attribute is None:
            return module if depth == len(parts) else None
        if hasattr(module, attribute):
            return getattr(module, attribute)
    return None


class _Unimplemented(type):
    """Metaclass of use-site capability sentinels for build123d names without a Bend implementation.

    A sentinel may be imported, compared by identity, subscripted as a type and
    used in annotations (``-> Sketch``, ``Part | None``, ``ShapeList[Edge]``).
    Everything that would need the real object raises the capability error
    where it happens.
    """

    def __new__(mcls, name, bases, namespace, **kwargs):
        if kwargs.pop("_wonky_sentinel", False):
            return super().__new__(mcls, name, bases, namespace)
        base = next(b for b in bases if isinstance(b, _Unimplemented))
        return base._wonky_fail(f"Subclassing {base._wonky_name}")

    def __init__(cls, name, bases, namespace, **kwargs):
        super().__init__(name, bases, namespace)

    def _wonky_fail(cls, what):
        return _unsupported(f"{what} is not implemented by the Python frontend{cls._wonky_note}")

    def __call__(cls, *args, **kwargs):
        return cls._wonky_fail(cls._wonky_name)

    def __getattr__(cls, name):
        if name.startswith("_"):
            raise AttributeError(name)
        gap = _KERNEL_GAPS.get(f"{cls._wonky_name.rsplit('.', 1)[-1]}.{name}")
        if gap is not None:  # e.g. Edge.make_spline: the note of the operation, not of the class
            return _unsupported(f"{cls._wonky_name}.{name} is not implemented by the Python frontend; {gap}")
        return cls._wonky_fail(f"{cls._wonky_name}.{name}")

    def __setattr__(cls, name, value):
        if name.startswith("_"):
            return super().__setattr__(name, value)
        return cls._wonky_fail(f"Assigning {cls._wonky_name}.{name}")

    def __instancecheck__(cls, instance):
        return cls._wonky_fail(f"isinstance() against {cls._wonky_name}")

    def __subclasscheck__(cls, subclass):
        return cls._wonky_fail(f"issubclass() against {cls._wonky_name}")

    def __getitem__(cls, item):
        if cls._wonky_kind in ("class", "alias"):
            return cls  # a parametrized type in an annotation builds nothing
        return cls._wonky_fail(f"{cls._wonky_name}[...]")

    def __repr__(cls):
        return f"<{cls._wonky_name}: not implemented by the Bend shim>"

    def _operator(verb):
        def fail(cls, *args):
            return cls._wonky_fail(f"{verb} {cls._wonky_name}")
        return fail

    # `|` stays type.__or__ so that `Part | None` annotations keep working.
    __bool__ = _operator("Truth value of")
    __iter__ = _operator("Iterating over")
    __len__ = _operator("len() of")
    __contains__ = _operator("Membership test in")
    __float__ = __int__ = __index__ = _operator("Converting")
    __neg__ = __pos__ = __abs__ = _operator("Arithmetic on")
    for _dunder in ("add", "sub", "mul", "matmul", "truediv", "floordiv", "mod", "pow", "and", "xor", "lshift",
                    "rshift"):
        locals()[f"__{_dunder}__"] = locals()[f"__r{_dunder}__"] = _operator("Arithmetic on")
    del _dunder, _operator


def _sentinel(qualname, entry):
    return _Unimplemented(qualname.rsplit(".", 1)[-1], (), {
        "__module__": qualname.rsplit(".", 1)[0], "__qualname__": qualname.rsplit(".", 1)[-1],
        "_wonky_name": qualname, "_wonky_kind": entry["kind"], "_wonky_note": _note(qualname.rsplit(".", 1)[-1], entry),
        "__doc__": f"{qualname}: not implemented by the Bend shim (build123d {__version__} {entry['kind']})",
    }, _wonky_sentinel=True)


def _bind(name, entry, qualname):
    """Value for one table entry: a frozen number or enum, the re-exported stdlib object, or a use-site sentinel."""
    if entry["kind"] == "value" and "value" in entry:
        return entry["value"]
    if entry["kind"] == "enum" and entry["origin"] in ("public", "build123d"):
        return _Enum(name, [(member, value) for member, value in entry["members"]],
                     module="build123d", qualname=name)
    if "stdlib" in entry:
        value = _stdlib(entry["stdlib"])
        if value is not None:
            return value
    return _sentinel(qualname, entry)


def _top(name):
    """A top-level build123d name, binding a lazy stdlib re-export on first use."""
    namespace = globals()
    if name not in namespace:
        namespace[name] = _bind(name, _TABLE["names"][name], f"build123d.{name}")
    return namespace[name]


def _submodule(fullname, spec):
    """A read-only view of build123d.<sub>: its public names resolve through the same table."""
    module = _types.ModuleType(fullname, f"Bend shim view of {fullname} (build123d {__version__} names)")
    module.__path__ = []
    # Every public attribute of the real submodule (constants, aliases, mixins,
    # re-exports), so `from build123d.<sub> import X` fails only where build123d fails.
    names = spec.get("names", {})
    # `import *` binds the declared __all__, or all public names of a module without one.
    declared = spec.get("all")
    module.__all__ = list(declared) if isinstance(declared, list) else list(names)

    def __getattr__(name):
        if name.startswith("_") or name not in names:
            raise AttributeError(f"module {fullname!r} has no attribute {name!r}")
        entry = names[name]
        if entry is not None and entry["origin"] == "submodule" and entry.get("module") in _sys.modules:
            value = _sys.modules[entry["module"]]  # another shim view, e.g. topology.one_d
        else:
            value = _top(name) if entry is None else _bind(name, entry, f"{fullname}.{name}")
        setattr(module, name, value)
        return value

    module.__getattr__ = __getattr__
    return module


def _install_names():
    namespace = globals()
    views = {}
    for fullname, spec in sorted(_TABLE["submodules"].items()):
        if spec.get("importable"):
            views[fullname] = _sys.modules[fullname] = _submodule(fullname, spec)
    for fullname, view in views.items():
        parent, _, child = fullname.rpartition(".")
        if parent in views:
            setattr(views[parent], child, view)
    for name, entry in _TABLE["names"].items():
        if name in namespace or "stdlib" in entry:
            continue  # implemented above, or a stdlib re-export bound on first use (module __getattr__)
        view = views.get(f"build123d.{name}")
        namespace[name] = view if view is not None and entry["origin"] == "submodule" else _bind(name, entry, f"build123d.{name}")


_install_names()


def _bind_class_attributes():
    """Implemented class attributes, also on names that stay sentinels (e.g. Solid.make_box on Solid)."""
    for qualname, value in _CLASS_ATTRIBUTES.items():
        owner_name, _, attribute = qualname.partition(".")
        owner = globals().get(owner_name)
        if owner is None or not attribute:
            raise RuntimeError(f"CLASS_ATTRIBUTES entry {qualname!r} does not name a build123d class attribute")
        if isinstance(owner, _Unimplemented):
            type.__setattr__(owner, attribute, value)  # the sentinel's __setattr__ refuses model assignments
        else:
            setattr(owner, attribute, value)


_bind_class_attributes()


class _KernelGap:
    """A build123d method of an implemented class whose operation the Bend kernel lacks (``Shape.mirror``).

    Reading it is the capability error, at its use site, like any other
    unimplemented attribute of an implemented class, but the message names the
    missing kernel operation.
    """

    def __init__(self, attribute, note):
        self._attribute, self._note = attribute, note

    def __get__(self, instance, owner=None):
        name = (type(instance) if instance is not None else owner).__name__
        return _unsupported(f"{name}.{self._attribute} is not implemented by the Python frontend; {self._note}")


def _install_kernel_gaps():
    """Bind _KernelGap descriptors on implemented classes; implemented attributes and sentinels are left alone."""
    namespace = globals()
    for qualname, note in _KERNEL_GAPS.items():
        owner_name, _, attribute = qualname.partition(".")
        owner = namespace.get(owner_name)
        if not attribute or owner is None or isinstance(owner, _Unimplemented):
            continue  # top-level names and sentinel classes carry the note in their own messages
        if not any(attribute in vars(klass) for klass in owner.__mro__):
            type.__setattr__(owner, attribute, _KernelGap(attribute, note))


_install_kernel_gaps()

# `from build123d import *` binds exactly build123d 0.13.0's public names.
__all__ = list(_TABLE["all"])


def __getattr__(name):
    if not name.startswith("_") and name in _TABLE["names"]:
        return _top(name)
    if name.startswith("_"):
        raise AttributeError(name)
    raise AttributeError(f"module 'build123d' has no attribute {name!r} (not a public name of build123d {__version__})")
