"""Eager build123d Algebra compatibility surface backed only by Bend.

Loaded by runner.py, never by an installed build123d or OpenCascade package.
Shape handles identify B-reps already constructed in the Node/Bend process.

This file is the loader. The implementation lives in private modules next to
it, loaded by path (files starting with "_" are not importable by models, and
frames in them count as shim frames for use-site locations):

- ``_b3d_core.py``: the host bridge, Shape, Box, Cylinder, Align, Mode,
  export_step/export_stl, and ``register_shape_method`` for Shape methods
  that other modules implement;
- ``_b3d_location.py``: Vector, Location, Rotation/Rot, Pos, Plane, Axis;
- further ``_b3d_*.py`` modules (sketch profiles, operations, queries) when
  present; a missing one is skipped, its names stay sentinels;
- ``_wonky_color.py``: Color.

Each module publishes ``BUILD123D = {name: object}`` (top-level names) and
optionally ``CLASS_ATTRIBUTES = {"Class.attribute": object}``; the core also
publishes ``SHIM_ATTRIBUTES`` (the bridge helpers the runner, _wonky_runtime
and cad_khana use as ``build123d._unsupported`` etc.).

The module binds every public name of build123d 0.13.0 (frozen with provenance
in build123d_names.json, generated by scripts/python/build123d-names.py).
A name is either implemented by those modules, bound to the very standard-library
object build123d re-exports (math.pi, typing.Any, pathlib.Path, ...), or bound
to a sentinel. A sentinel constructs nothing, so importing it or naming it in an
annotation succeeds; calling it, reading its attributes, isinstance()/
issubclass() against it, subclassing it or using it as a value raises a
capability error at that use site (line and column). Names that build123d
0.13.0 does not have, including enum members it lacks, raise
AttributeError/ImportError, as the real package does.
"""

