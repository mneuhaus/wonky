// Next-blocker experiment for the corpus cluster "py-imports"
// (docs/corpus/cluster-py-imports.md).
//
// The production Python runner starts `python -I -S -B -u python/runner.py`
// and execs the model source from a JSON message. Neither the model's
// directory nor any site-packages directory is on sys.path, so
// `import params` and `import numpy` fail. This script measures what each
// affected corpus file hits once that is fixed, WITHOUT touching production:
//
//   - A patched COPY of python/runner.py is generated into tmp/corpus/py-imports/
//     (three textual patches, listed at the patch site below).
//   - A wrapper interpreter (tmp/corpus/py-imports/python-next) is passed as
//     the production `--python` option. It swaps the runner path for the
//     patched copy, optionally drops -S, selects the interpreter through
//     `uv run --no-project --python <venv python> python`, and runs Python in
//     a macOS sandbox that denies writes below the corpus root.
//   - Each unit goes through scripts/corpus/probe.mjs, i.e. the production
//     src/python.mjs buildPython with the production shim, host session and
//     classifier (scripts/corpus/lib.mjs).
//
// Variants:
//   dir      model directory on sys.path; -S kept; base uv interpreter
//            (the environment of the corpus run).
//   dir+env  model directory on sys.path; -S dropped (-I kept); the project's
//            own .venv, chosen as Marc runs these files: a docstring hint
//            `uv run --project <p>`, else the nearest ancestor .venv, else
//            cad-project-043/pruefstand (the environment the r10 handoff uses).
//   dir+env+lazy  dir+env, plus the stage-1 fix of cluster py-api-surface
//            emulated inside the runner copy: every build123d 0.13 public name
//            is bound to the shim's own _UnsupportedAPI capability sentinel
//            (the same emulation as scripts/corpus/py-api-surface/lazy.py, but
//            in the runner, so sibling modules see it too and no model copy is
//            needed). Shows the blocker after BOTH frontend fixes.
//
// Usage: node scripts/corpus/py-imports-next.mjs [--variant dir|dir+env|dir+env+lazy] [--only substr[,substr...]] [--rest]
//          [--in-place] [--concurrency 2] [--out name.jsonl]
// Writes out/corpus/py-imports-next.jsonl (--rest: py-imports-next-rest.jsonl; a single
// --variant or --only: py-imports-next.partial.jsonl; --out overrides), replaced, and prints a summary.
import { readFileSync, writeFileSync, existsSync, mkdirSync, chmodSync } from 'node:fs';
import { spawn, execFileSync } from 'node:child_process';
import { join, dirname, relative } from 'node:path';
import { REPO, CORPUS_ROOT, OUT_DIR, TMP_DIR, RUNS, classify, messagePattern } from './lib.mjs';

const args = process.argv.slice(2);
const opt = (name, fallback) => { const i = args.indexOf(name); return i >= 0 ? args[i + 1] : fallback; };
const variants = opt('--variant') ? [opt('--variant')] : ['dir', 'dir+env'];
const only = opt('--only');
const concurrency = Math.min(3, Number(opt('--concurrency', 2)));
const TIMEOUT_MS = 120000;
if (process.env.WONKY_BACKEND) throw new Error('WONKY_BACKEND is set; corpus runs must use the default JS path');

const b3dVocab = new Set(Object.keys(JSON.parse(readFileSync(join(REPO, 'fixtures/lang/b3d-vocab.json'), 'utf8')).categories ?? {}));
const WORK = join(TMP_DIR, 'py-imports');
const MIRROR = join(TMP_DIR, 'src');
// --in-place: run the corpus file where it lives (for data files the mirror does not
// copy: > 1 MiB, .step, .brd). Python stays in the sandbox that denies writes below
// the corpus root, and -B prevents bytecode writes, so the corpus is only read.
const SRC_ROOT = args.includes('--in-place') ? CORPUS_ROOT : MIRROR;
mkdirSync(join(WORK, 'work'), { recursive: true });

// ---------------------------------------------------------------- patched runner copy
const production = readFileSync(join(REPO, 'python/runner.py'), 'utf8');
const shimAnchor = 'Path(__file__).with_name("build123d.py")';
const fileAnchor = '    filename = initial["filename"]\n';
const packageAnchor = 'spec.loader.exec_module(shim)\n';
if (![shimAnchor, fileAnchor, packageAnchor].every(a => production.includes(a))) throw new Error('python/runner.py changed; update the patch anchors');
// Patches: (1) absolute shim path, (2) the shim becomes a package with no
// submodules, so `import build123d.x` reaches NoExternalGeometry (capability
// error) instead of stopping at "'build123d' is not a package", (3) the model
// directory on sys.path[0] and sys.argv = [filename], as `python model.py`.
const patched = '# GENERATED by scripts/corpus/py-imports-next.mjs from python/runner.py. Experiment only, never production.\n'
  + production
    .replace(shimAnchor, `Path(${JSON.stringify(join(REPO, 'python/build123d.py'))})`)
    .replace(packageAnchor, packageAnchor + 'shim.__path__ = []\n')
    .replace(fileAnchor, fileAnchor
      + '    if os.path.isfile(filename):\n'
      + '        sys.path.insert(0, os.path.dirname(os.path.abspath(filename)))\n'
      + '        sys.argv = [filename]\n');
const RUNNER = join(WORK, 'runner_next.py');
writeFileSync(RUNNER, patched);

// dir+env+lazy: the py-api-surface stage-1 emulation (lazy, complete name
// table) added to the runner copy right after the shim is loaded. The name
// list is build123d 0.13.0 `__all__` (203 names), frozen by the py-api-surface
// analysis in tmp/corpus/py-api-surface/b3d-all.json; read only.
const B3D_ALL_FILE = join(TMP_DIR, 'py-api-surface/b3d-all.json');
const RUNNER_LAZY = join(WORK, 'runner_deep.py');
if (variants.some(v => v.endsWith('+lazy'))) {
  const b3dAll = JSON.parse(readFileSync(B3D_ALL_FILE, 'utf8'));
  const lazy = 'shim.__all__ = sorted(set(shim.__all__) | set(' + JSON.stringify(b3dAll) + '))\n'
    + 'def _wk_lazy(name, _shim=shim):\n'
    + '    if name.startswith("_"):\n'
    + '        raise AttributeError(name)\n'
    + '    return _shim._UnsupportedAPI(name)\n'
    + 'shim.__getattr__ = _wk_lazy\n';
  writeFileSync(RUNNER_LAZY, patched
    .replace('Experiment only, never production.', 'Experiment only, never production. Variant dir+env+lazy.')
    .replace(packageAnchor + 'shim.__path__ = []\n', packageAnchor + 'shim.__path__ = []\n' + lazy));
}

const WRAPPER = join(WORK, 'python-next');
writeFileSync(WRAPPER, `#!/bin/bash
# GENERATED by scripts/corpus/py-imports-next.mjs. Stand-in for the production
# --python option: swaps the runner for the patched copy, optionally drops -S,
# and denies writes below the corpus root.
out=()
for a in "$@"; do
  case "$a" in
    -S) [ "$WONKY_NEXT_SITE" = 1 ] && continue ;;
    */python/runner.py) a="$WONKY_NEXT_RUNNER" ;;
  esac
  out+=("$a")
done
interp=()
[ -n "$WONKY_NEXT_INTERP" ] && interp=(--python "$WONKY_NEXT_INTERP")
exec /usr/bin/sandbox-exec -p '(version 1)(allow default)(deny file-write* (subpath "'"$WONKY_NEXT_CORPUS"'"))' \\
  uv run --no-project --quiet "\${interp[@]}" python "\${out[@]}"
`);
chmodSync(WRAPPER, 0o755);

// ---------------------------------------------------------------- units
const latest = new Map();
for (const line of readFileSync(RUNS, 'utf8').trim().split('\n')) { const r = JSON.parse(line); latest.set(r.key, r); }
// --rest: the other Python units (not in this cluster), as a regression check
// that the proposed runner change leaves their first blocker unchanged.
const rest = args.includes('--rest');
const units = [...latest.values()]
  .filter(r => r.frontend === 'py' && (rest ? r.kind !== 'python-import' : r.kind === 'python-import'))
  .filter(r => !only || only.split(',').some(o => r.path.includes(o)));

const venvOf = dir => existsSync(join(dir, '.venv/pyvenv.cfg')) ? join(dir, '.venv/bin/python') : null;
function chooseEnv(path) {
  const text = readFileSync(join(SRC_ROOT, path), 'utf8').slice(0, 4000);
  const hint = text.match(/uv run --project (\S+)/);
  if (hint) {
    const p = hint[1].startsWith('/') ? hint[1] : join(CORPUS_ROOT, hint[1]);
    if (venvOf(p)) return { interp: venvOf(p), env: relative(CORPUS_ROOT, p), reason: 'docstring uv run --project' };
  }
  for (let d = dirname(join(CORPUS_ROOT, path)); d.startsWith(CORPUS_ROOT) && d !== CORPUS_ROOT; d = dirname(d)) {
    if (venvOf(d)) return { interp: venvOf(d), env: relative(CORPUS_ROOT, d), reason: 'nearest ancestor .venv' };
  }
  const fallback = join(CORPUS_ROOT, 'cad-project-043/pruefstand');
  return { interp: venvOf(fallback), env: 'cad-project-043/pruefstand', reason: 'default (r10 handoff uses it)' };
}

function probe(unit, variant) {
  const file = join(SRC_ROOT, unit.path);
  const withEnv = variant.startsWith('dir+env');
  const env = withEnv ? chooseEnv(unit.path) : { interp: '', env: '(uv --no-project base)', reason: 'corpus run environment' };
  const cwd = join(WORK, 'work', unit.path.replace(/\//g, '_'));
  mkdirSync(cwd, { recursive: true });
  return new Promise(done => {
    const t0 = Date.now();
    const child = spawn(process.execPath, [join(REPO, 'scripts/corpus/probe.mjs'), 'py', file, WRAPPER, String(TIMEOUT_MS - 10000)], {
      cwd, detached: true, stdio: ['ignore', 'pipe', 'pipe'],
      env: { ...process.env, WONKY_NEXT_SITE: withEnv ? '1' : '0', WONKY_NEXT_INTERP: env.interp,
        WONKY_NEXT_RUNNER: variant.endsWith('+lazy') ? RUNNER_LAZY : RUNNER, WONKY_NEXT_CORPUS: CORPUS_ROOT },
    });
    let out = '', err = '';
    child.stdout.on('data', c => { out += c; });
    child.stderr.on('data', c => { err += c; });
    const timer = setTimeout(() => { try { process.kill(-child.pid, 'SIGKILL'); } catch {} }, TIMEOUT_MS);
    child.on('close', (code, signal) => {
      clearTimeout(timer);
      let p = null;
      try { p = JSON.parse(out.trim().split('\n').pop()); } catch {}
      const message = p?.message ?? (signal ? `killed by ${signal}` : err.trim().slice(-500));
      let { status, kind } = p?.ok ? { status: 'ok', kind: 'ok' }
        : signal ? { status: 'timeout', kind: 'runner-timeout' }
        : classify({ errorClass: p?.errorClass, message, userThrow: false, completedOperations: p?.trace?.completed ?? 0 });
      const module = kind === 'python-import' ? (message.match(/No module named '([^'.]+)/) ?? [])[1] ?? null : null;
      // Same refinement as summarize.mjs normalize(): a wildcard-imported
      // build123d name the shim does not export is an API-surface gap.
      const name = kind === 'python-name-error' ? (message.match(/name '([^']+)' is not defined/) ?? [])[1] : null;
      if (name && b3dVocab.has(name)) { status = 'capability'; kind = 'python-api-wildcard'; }
      // The traceback tells whether the failure is in the model or inside an imported module.
      const frames = [...(p?.traceback ?? '').matchAll(/File "([^"]+)", line (\d+)/g)].map(m => ({ file: m[1], line: Number(m[2]) }));
      const deepest = frames.filter(f => !f.file.includes('/wonky-kernel/python/') && !f.file.includes('runner_next.py')).pop() ?? null;
      done({
        schema: 'corpus-py-imports-next/1', variant, key: unit.key, path: unit.path, family: unit.family,
        env: env.env, envReason: env.reason, firstBlocker: { message: unit.message, line: unit.location?.line ?? null },
        wallMs: Date.now() - t0, status, kind, module, errorClass: p?.errorClass ?? null, message: String(message).slice(0, 600),
        pattern: messagePattern(message), line: p?.line ?? null, sourceLine: p?.sourceLine ?? null,
        completedRequests: p?.trace?.completed ?? 0,
        failingFrame: deepest ? { file: deepest.file.replace(MIRROR + '/', 'mirror:').replace(CORPUS_ROOT + '/', 'corpus:'), line: deepest.line } : null,
        tracebackTail: p?.traceback ? p.traceback.split('\n').slice(-6).join('\n') : null,
      });
    });
  });
}

const uptime = () => execFileSync('uptime', { encoding: 'utf8' }).trim();
const meta = { startedAt: new Date().toISOString(), uptimeStart: uptime(), variants, source: SRC_ROOT === MIRROR ? 'mirror' : 'in-place (sandboxed, read-only)', units: units.length, concurrency, timeoutMs: TIMEOUT_MS,
  head: execFileSync('git', ['-C', REPO, 'rev-parse', '--short', 'HEAD'], { encoding: 'utf8' }).trim() };
const jobs = variants.flatMap(v => units.map(u => [u, v]));
const results = [];
let next = 0;
await Promise.all(Array.from({ length: concurrency }, async () => {
  while (next < jobs.length) {
    const [u, v] = jobs[next++];
    const r = await probe(u, v);
    results.push(r);
    process.stderr.write(`${v.padEnd(8)} ${r.status.padEnd(10)} ${r.kind.padEnd(28)} ${u.path}  ${r.message.slice(0, 110)}\n`);
  }
}));
meta.finishedAt = new Date().toISOString();
meta.uptimeEnd = uptime();
const outFile = join(OUT_DIR, opt('--out') ?? (rest ? 'py-imports-next-rest.jsonl' : only || opt('--variant') ? 'py-imports-next.partial.jsonl' : 'py-imports-next.jsonl'));
writeFileSync(outFile, [JSON.stringify({ meta }), ...results.sort((a, b) => a.variant.localeCompare(b.variant) || a.path.localeCompare(b.path)).map(r => JSON.stringify(r))].join('\n') + '\n');
for (const v of variants) {
  const rs = results.filter(r => r.variant === v), count = {};
  for (const r of rs) count[`${r.status}/${r.kind}`] = (count[`${r.status}/${r.kind}`] ?? 0) + 1;
  console.log(v, JSON.stringify(count));
}
console.log(outFile, JSON.stringify(meta));
