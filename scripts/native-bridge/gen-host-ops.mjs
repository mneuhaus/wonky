#!/usr/bin/env node
// One numeric registry: rust/wonky-ops/host-operations.json. JS reads it directly;
// Rust uses the generated block in host.rs (kept in-tree for ordinary Cargo builds).
import fs from 'node:fs';
import {fileURLToPath} from 'node:url';

export const BEGIN = '// BEGIN GENERATED HOST OPERATIONS';
export const END = '// END GENERATED HOST OPERATIONS';
const registryFile = new URL('../../rust/wonky-ops/host-operations.json', import.meta.url);
const hostFile = new URL('../../rust/wonky-ops/src/host.rs', import.meta.url);

export function rustHostOperationBlock(registry) {
  const operations = registry.operations.map(({name, number, documentation = []}) => [
    ...documentation.map(line => `    /// ${line}`),
    `    pub const OP_${name}: u32 = ${number};`,
  ].join('\n')).join('\n');
  return `${BEGIN}
// Generated by scripts/native-bridge/gen-host-ops.mjs; do not edit this block.
// New operations take max+1 at merge time; see ../host-operations.json.
// The macro enumerates EVERY constant for the unit uniqueness test, including
// newly added operations not yet used by a dispatch match arm.
macro_rules! define_host_operations {
    ($( $(#[$meta:meta])* pub const $name:ident: u32 = $number:literal; )*) => {
        $( $(#[$meta])* pub const $name: u32 = $number; )*
        pub const HOST_OPERATION_NUMBERS: &[(&str, u32)] = &[
            $( (stringify!($name), $name), )*
        ];
    };
}
define_host_operations! {
${operations}
}
${END}`;
}

export function generatedHostSource(source, registry) {
  const start = source.indexOf(BEGIN), end = source.indexOf(END);
  if (start < 0 || end < start || source.indexOf(BEGIN, start + BEGIN.length) >= 0 || source.indexOf(END, end + END.length) >= 0) {
    throw new Error('HOST_OPERATION_GENERATION_MARKERS_INVALID');
  }
  return source.slice(0, start) + rustHostOperationBlock(registry) + source.slice(end + END.length);
}

if (process.argv[1] && fs.existsSync(process.argv[1]) && fileURLToPath(import.meta.url) === fs.realpathSync(process.argv[1])) {
  const args = process.argv.slice(2);
  if (args.some(arg => arg !== '--check') || args.length > 1) throw new Error('usage: gen-host-ops.mjs [--check]');
  const registry = JSON.parse(fs.readFileSync(registryFile, 'utf8'));
  const source = fs.readFileSync(hostFile, 'utf8');
  const generated = generatedHostSource(source, registry);
  if (args.includes('--check')) {
    if (source !== generated) {
      console.error('HOST_OPERATIONS_STALE: run node scripts/native-bridge/gen-host-ops.mjs');
      process.exitCode = 1;
    }
  } else if (source !== generated) fs.writeFileSync(hostFile, generated);
}
